function updateTrack(track, occurence) {
  const newTrack = [];
  for (let i = 0; i < track.length; i++) {
    const n = occurence.has(i) ? occurence.get(i) : 0;
    for (let j = 0; j < n; j++) newTrack.push(track[i]);
  }
  return newTrack;
}

