const Ts = [T1, T2, T3];

function buildRules(T) {
  return T.map(([pat, rep, changes]) => [new RegExp(pat), rep, changes]);
}

function buildCombinedPattern(rules) {
  const combined = rules.map(([pat], i) => `(?<R${i}>${pat.source})`).join("|");
  return new RegExp(combined, "g");
}

const allRules = Ts.map(buildRules);
const allPatterns = Ts.map((_, ti) => buildCombinedPattern(allRules[ti]));

function ph1T(aya, { attachLawasiq = false } = {}) {
  if (aya == null) throw new Error("aya is required");
  if (aya[0] !== "$" || aya[aya.length - 1] !== "$") {
    throw new Error("The aya should start and finish with $ sign");
  }

  let track = Array.from({ length: aya.length }, (_, i) => i);
  if (attachLawasiq) {
    for (let i = 1; i < aya.length; i++) {
      if (lawasiq.includes(aya[i])) track[i] = track[i - 1];
    }
  }

  let result = aya;

  for (let ti = 0; ti < Ts.length; ti++) {
    const rules = allRules[ti];
    const T = Ts[ti];

    const occurence = new Map();
    for (let i = 0; i < track.length; i++) occurence.set(i, 1);

    const combined = new RegExp(allPatterns[ti].source, "g");

    result = result.replace(combined, function (match, ...args) {
      const groups = args[args.length - 1];
      let ruleIdx = -1;
      for (const key of Object.keys(groups)) {
        if (groups[key] !== undefined && key.startsWith("R")) {
          ruleIdx = parseInt(key.slice(1));
          break;
        }
      }
      if (ruleIdx < 0) return match;

      const start = args[args.length - 3];
      const len = match.length;
      const [pat, replacement, changes] = rules[ruleIdx];

      for (const [idx, occ] of changes) {
        const absIdx = idx >= 0 ? start + idx : start + idx + len;
        occurence.set(absIdx, occ);
      }

      return match.replace(new RegExp(pat.source), replacement);
    });

    track = updateTrack(track, occurence);
  }

  return [result, track];
}

